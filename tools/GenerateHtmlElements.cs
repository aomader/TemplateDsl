// Generates the HTML elements and the static class H from src/TemplateDsl.Html/elements.txt.
//
//   dotnet run tools/GenerateHtmlElements.cs           writes the files
//   dotnet run tools/GenerateHtmlElements.cs --check   fails if they are out of date

using System.Globalization;
using System.Runtime.CompilerServices;
using System.Text;

var project = Path.GetFullPath(Path.Combine(ThisFile(), "..", "..", "src", "TemplateDsl.Html"));
var (global, elements) = Parse(File.ReadAllLines(Path.Combine(project, "elements.txt")));

var outputs = new Dictionary<string, string>
{
    [Path.Combine(project, "Elements", "Elements.Generated.cs")] = EmitElements(global, elements),
    [Path.Combine(project, "H.Generated.cs")] = EmitTags(elements),
};

if (args.Contains("--check"))
{
    var stale = outputs.Where(o => !File.Exists(o.Key) || File.ReadAllText(o.Key) != o.Value).Select(o => o.Key).ToArray();

    foreach (var path in stale)
    {
        Console.Error.WriteLine($"Out of date: {path}");
    }

    return stale.Length == 0 ? 0 : 1;
}

foreach (var (path, content) in outputs)
{
    File.WriteAllText(path, content);
}

Console.WriteLine($"Generated {elements.Count} elements.");
return 0;

static string ThisFile([CallerFilePath] string path = "") => path;

static (List<Attribute> Global, List<Element> Elements) Parse(string[] lines)
{
    var global = new List<Attribute>();
    var elements = new List<Element>();

    foreach (var line in lines.Select(l => l.Trim()).Where(l => l.Length > 0 && !l.StartsWith('#')))
    {
        var parts = line.Split(':', 2);
        var name = parts[0].Trim();
        var attributes = parts[1].Split(' ', StringSplitOptions.RemoveEmptyEntries).Select(ParseAttribute).ToList();

        if (name == "global")
        {
            global = attributes;
        }
        else
        {
            var tag = name.TrimEnd('!').Split('.', 2);
            elements.Add(new Element(tag[0], tag.Length > 1 ? tag[1] : null, name.EndsWith('!'), attributes, global));
        }
    }

    return (global, elements);
}

static Attribute ParseAttribute(string text)
{
    var parts = text.Split(':', 2);
    var name = parts[0].TrimEnd('?', '~');

    return new Attribute(name, parts[0].EndsWith('?'), parts[0].EndsWith('~'), parts.Length > 1 ? parts[1] : null);
}

static string EmitElements(List<Attribute> global, List<Element> elements)
{
    var source = new StringBuilder("// <auto-generated>Generated by tools/GenerateHtmlElements.cs from elements.txt. Do not edit.</auto-generated>\n#nullable enable\n\nnamespace TemplateDsl.Html.Elements;\n");

    source.Append("\n/// <summary>The attributes that every element has. Each returns the element itself, <typeparamref name=\"TElement\"/>.</summary>\n");
    source.Append(Coverage.Excluded + "\npublic abstract partial class HtmlTag<TElement> : HtmlElement where TElement : HtmlTag<TElement>\n{\n    private protected HtmlTag() { }\n\n");
    EmitAttributes(source, "TElement", global);
    source.Append("    /// <summary>An attribute without its own method, such as <c>data-id</c>. The name must be a constant.</summary>\n");
    source.Append("    [AttrList(Before = \" \", BetweenNameAndValue = \"=\\\"\", After = \"\\\"\", Escape = \"attribute\", CurrentCultureNames = new[] { \"aria-label\", \"aria-description\", \"aria-placeholder\", \"aria-roledescription\", \"aria-valuetext\" })]\n");
    source.Append("    public partial TElement Attr(string name, string? value);\n}\n");

    foreach (var element in elements)
    {
        source.Append(CultureInfo.InvariantCulture, $"\n/// <summary>{element.Summary}</summary>\n");
        source.Append(CultureInfo.InvariantCulture, $"[Node(Start = \"{element.Start.Replace("\"", "\\\"")}\", Body = \">\"");
        source.Append(element.IsVoid ? ", IsVoid = true" : $", End = \"</{element.Name}>\"");
        source.Append(CultureInfo.InvariantCulture, $")]\n{Coverage.Excluded}\npublic sealed partial class {element.ClassName} : HtmlTag<{element.ClassName}>\n{{\n    internal {element.ClassName}() {{ }}\n");

        if (element.Attributes.Count > 0)
        {
            source.Append('\n');
            EmitAttributes(source, element.ClassName, element.Attributes);
            source.Length -= 1;
        }

        source.Append("}\n");
    }

    return source.ToString();
}

static void EmitAttributes(StringBuilder source, string returnType, List<Attribute> attributes)
{
    foreach (var attribute in attributes)
    {
        // Every attribute with a value is escaped, also numbers and dates: a number can be of the app's own type,
        // which writes whatever its formatting says, and a value without special characters costs only a check.
        var (attr, parameter) = attribute switch
        {
            { IsBool: true } => ($"[Attr(\" {attribute.Name}\", \"\")]", "bool? value = true"),
            { Type: "any" or null } => (
                $"[Attr(\" {attribute.Name}=\\\"\", \"\\\"\", Escape = \"attribute\"{(attribute.IsForPeople ? ", Culture = ValueCulture.Current" : attribute.Type is null ? ", TextOnly = true" : "")})]",
                "string? value"),
            _ => attribute.Type switch
            {
                "number" => ($"[Attr(\" {attribute.Name}=\\\"\", \"\\\"\", Escape = \"attribute\", AnyNumber = true)]", "double? value"),
                "number|text" => ($"[Attr(\" {attribute.Name}=\\\"\", \"\\\"\", Escape = \"attribute\", AnyNumber = true, AlsoText = true)]", "double? value"),
                "month" => ($"[Attr(\" {attribute.Name}=\\\"\", \"\\\"\", Escape = \"attribute\", Format = \"yyyy-MM\")]", "System.DateOnly? value"),
                var type => ($"[Attr(\" {attribute.Name}=\\\"\", \"\\\"\", Escape = \"attribute\")]", type switch
                {
                    "date" => "System.DateOnly",
                    "time" => "System.TimeOnly",
                    "datetime" => "System.DateTime",
                    var other => other,
                } + "? value"),
            },
        };

        source.Append(CultureInfo.InvariantCulture, $"    /// <summary>The <c>{attribute.Name}</c> attribute.{(attribute.IsForPeople ? " Numbers and dates in it use the current culture, because it's meant for people to read." : "")}</summary>\n");
        source.Append(CultureInfo.InvariantCulture, $"    {attr}\n    public partial {returnType} {attribute.MethodName}({parameter});\n\n");
    }
}

static string EmitTags(List<Element> elements)
{
    var source = new StringBuilder("// <auto-generated>Generated by tools/GenerateHtmlElements.cs from elements.txt. Do not edit.</auto-generated>\n#nullable enable\n\nnamespace TemplateDsl.Html;\n\n" + Coverage.Excluded + "\npublic static partial class H\n{");

    foreach (var element in elements)
    {
        source.Append(CultureInfo.InvariantCulture, $"\n    /// <summary>{element.Summary}</summary>\n");
        source.Append(CultureInfo.InvariantCulture, $"    public static Elements.{element.ClassName} {element.FactoryName} => new();\n");
    }

    return source.Append("}\n").ToString();
}

sealed record Attribute(string Name, bool IsBool, bool IsForPeople, string? Type)
{
    public string MethodName => Names.Method(Name);
}

/// <param name="Name">The name of the element, such as <c>input</c>.</param>
/// <param name="Variant">For a variant of an element, such as the email input: the value of its type attribute.</param>
/// <param name="IsVoid">Whether it has no children, such as <c>br</c>.</param>
/// <param name="Attributes">The attributes of its own.</param>
/// <param name="Global">The attributes that every element has.</param>
sealed record Element(string Name, string? Variant, bool IsVoid, List<Attribute> Attributes, List<Attribute> Global)
{
    public string Start => Variant is null ? $"<{Name}" : $"<{Name} type=\"{Variant}\"";

    public string FactoryName => Names.Pascal(Name) + (Variant is null ? "" : Names.Pascal(Variant));

    public string Summary => Variant is null
        ? $"The <c>&lt;{Name}&gt;</c> element."
        : $"The <c>&lt;{Name} type=\"{Variant}\"&gt;</c> element, which takes only what this type allows.";

    /// <summary>A class can't declare a method with its own name. Inherited ones, such as the global title attribute, are fine.</summary>
    public string ClassName =>
        Variant is not null ? Names.Pascal(Variant) + Names.Pascal(Name)
        : Attributes.Any(a => a.MethodName == Names.Pascal(Name)) ? Names.Pascal(Name) + "Element"
        : Names.Pascal(Name);
}

/// <summary>Names in C# are PascalCase, which also keeps them apart from the keywords, such as class and for.</summary>
static class Names
{
    public static string Pascal(string name) =>
        string.Concat(name.Split('-').Select(part => char.ToUpperInvariant(part[0]) + part[1..]));

    /// <summary>An attribute of several words is cased like its DOM property, such as tabIndex: <c>TabIndex</c>.</summary>
    public static string Method(string attribute) => Words.TryGetValue(attribute, out var method) ? method : Pascal(attribute);

    private static readonly Dictionary<string, string> Words = new[]
    {
        "AccessKey", "ColSpan", "ContentEditable", "CrossOrigin", "DateTime", "DirName", "FormAction", "FormEnctype", "FormMethod",
        "FormNoValidate", "FormTarget", "InputMode", "IsMap", "MaxLength", "MinLength", "NoModule", "NoValidate", "PlaysInline",
        "PopoverTarget", "PopoverTargetAction", "ReadOnly", "ReferrerPolicy", "RowSpan", "TabIndex", "UseMap",
    }.ToDictionary(method => method.ToLowerInvariant());
}

static class Coverage
{
    /// <summary>
    /// Elements, their attributes and the factories in H only describe a template in Build, which is compiled and
    /// never runs, so code coverage leaves them out.
    /// </summary>
    public const string Excluded = "[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]";
}
